import { Router } from 'express';
import { requireFeature, requirePermission } from '../auth/middleware.js';
import { settingsRouter } from './settings/routes.js';
import { usersRouter } from './users/routes.js';
import { customersRouter } from './customers/routes.js';
import { assetsRouter } from './assets/routes.js';
import { requestsRouter } from './requests/routes.js';
import { workOrdersRouter } from './workorders/routes.js';
import { techniciansRouter } from './technicians/routes.js';
import { dispatchRouter } from './dispatch/routes.js';
import { quotationsRouter } from './quotations/routes.js';
import { invoicesRouter } from './invoices/routes.js';
import { einvoiceRouter } from './einvoice/routes.js';
import { paymentsRouter } from './payments/routes.js';
import { inventoryRouter } from './inventory/routes.js';
import { amcRouter } from './amc/routes.js';
import { calendarRouter } from './calendar/routes.js';
import { dashboardRouter } from './dashboard/routes.js';
import { reportsRouter } from './reports/routes.js';
import { notificationsRouter } from './notifications/routes.js';
import { supportRouter } from './support/routes.js';
import { documentsRouter } from './documents/routes.js';
import { aiRouter } from './ai/routes.js';
import { subscriptionRouter } from './subscriptions/routes.js';
import { integrationsRouter } from './integrations/routes.js';
import { auditRouter } from './audit/routes.js';
import { privacyRouter } from './privacy/routes.js';
import { searchRouter } from './search/routes.js';

/** All tenant (business) APIs. Mounted under /api/app behind authenticate + requireStaff + subscriptionGuard. */
export const tenantRouter = Router();
tenantRouter.use('/settings', settingsRouter);
tenantRouter.use('/users', usersRouter);
tenantRouter.use('/customers', requireFeature('crm'), customersRouter);
tenantRouter.use('/assets', requireFeature('crm'), assetsRouter);
tenantRouter.use('/requests', requireFeature('service_requests'), requestsRouter);
tenantRouter.use('/work-orders', requireFeature('work_orders'), workOrdersRouter);
tenantRouter.use('/technicians', techniciansRouter);
tenantRouter.use('/dispatch', requirePermission('dispatch.manage', 'work_orders.assign'), dispatchRouter);
tenantRouter.use('/quotations', requireFeature('quotations'), quotationsRouter);
tenantRouter.use('/invoices', requireFeature('invoicing'), invoicesRouter);
tenantRouter.use('/payments', requireFeature('invoicing'), paymentsRouter);
tenantRouter.use('/einvoice', requireFeature('invoicing'), einvoiceRouter);
tenantRouter.use('/inventory', requireFeature('inventory'), inventoryRouter);
tenantRouter.use('/amc', requireFeature('amc'), amcRouter);
tenantRouter.use('/calendar', calendarRouter);
tenantRouter.use('/dashboard', dashboardRouter);
tenantRouter.use('/reports', reportsRouter);
tenantRouter.use('/notifications', notificationsRouter);
tenantRouter.use('/support', supportRouter);
tenantRouter.use('/documents', documentsRouter);
tenantRouter.use('/ai', requireFeature('ai'), aiRouter);
tenantRouter.use('/subscription', subscriptionRouter);
tenantRouter.use('/integrations', integrationsRouter);
tenantRouter.use('/audit-logs', requirePermission('audit.read'), auditRouter);
tenantRouter.use('/privacy', requirePermission('privacy.manage'), privacyRouter);
tenantRouter.use('/search', searchRouter);
